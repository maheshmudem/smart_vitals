  static Map<String, MarkerSpec>? _index;
  static Map<String, AlgorithmCard>? _cardIndex;

  static Map<String, MarkerSpec> get _byCode {
    if (_index != null) return _index!;
    final m = <String, MarkerSpec>{};
    for (final c in cards) {
      for (final o in c.outputs) {
        m[o.code] = o;
        for (final a in o.aliases) {
          m.putIfAbsent(a, () => o);
        }
      }
    }
    return _index = m;
  }

  static Map<String, AlgorithmCard> get _cardsById {
    if (_cardIndex != null) return _cardIndex!;
    final m = <String, AlgorithmCard>{};
    for (final c in cards) {
      m[c.id] = c;
      for (final o in c.outputs) {
        m.putIfAbsent(o.algorithmId, () => c);
      }
    }
    return _cardIndex = m;
  }

  /// Spec for a code or legacy alias, e.g. `'MAP'` → `map_mmhg`.
  static MarkerSpec? byCode(String code) => _byCode[code];

  static AlgorithmCard? card(String algorithmId) => _cardsById[algorithmId];

  static AlgorithmCard? cardOf(String code) {
    final s = byCode(code);
    return s == null ? null : card(s.algorithmId);
  }

  /// Cards for a list of algorithm ids; ids may be ranges such as
  /// `'ALG-DEN-01..07'` or single members such as `'ALG-HRV-02'`.
  static List<AlgorithmCard> cardsFor(Iterable<String> algorithmIds) {
    final out = <AlgorithmCard>[];
    for (final id in algorithmIds) {
      final c = card(id);
      if (c != null && !out.contains(c)) out.add(c);
    }
    return out;
  }

