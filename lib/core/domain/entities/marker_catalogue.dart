import 'enums.dart';

/// How the spec says a marker reaches the member (Doc 09 "Output Markers").
enum MarkerDisplay {
  /// Numeric / enum value is member-facing.
  shown,

  /// Only the band word is member-facing (G-24 band-only release).
  bandOnly,

  /// Spec says "internal only" — never member-facing (R-9).
  internal,

  /// Diagnostic intermediate kept for operator QA only.
  diagnostic,

  /// Internal until the numeric validation study passes (SBP / DBP).
  internalUntilValidated,
}

enum MarkerKind { number, band, classCode, flag, list, text }

/// Optional numeric gauge for the marker detail (only where the spec states
/// numeric cut-offs).
class MarkerThresholds {
  const MarkerThresholds({
    required this.breakpoints,
    required this.labels,
    required this.bands,
  });

  /// `labels.length + 1` ascending breakpoints.
  final List<double> breakpoints;
  final List<String> labels;

  /// Band per segment (drives the segment colour).
  final List<SemanticBand> bands;
}

/// One output marker exactly as the algorithm card lists it.
class MarkerSpec {
  const MarkerSpec({
    required this.code,
    required this.label,
    required this.algorithmId,
    required this.specRef,
    required this.display,
    required this.kind,
    this.unit = '',
    this.decimals = 0,
    this.validMin,
    this.validMax,
    this.normalRange,
    this.allowedValues = const [],
    this.conditions = const [],
    this.aliases = const [],
    this.howComputed = '',
    this.thresholds,
    this.missingReason,
    this.threshold,
  });

  final String code;
  final String label;
  final String algorithmId;

  /// Spec paragraph, e.g. '§4.1'.
  final String specRef;
  final MarkerDisplay display;
  final MarkerKind kind;
  final String unit;
  final int decimals;
  final double? validMin;
  final double? validMax;

  /// Spec normal / screening range text; null → "Reference range not yet
  /// available" (medical safety rule, §4.3 / §4.8).
  final String? normalRange;

  /// Band / class enum strings from the spec.
  final List<String> allowedValues;
  final List<String> conditions;

  /// Legacy or per-side session keys that map onto this spec marker.
  final List<String> aliases;
  final String howComputed;
  final MarkerThresholds? thresholds;

  /// Spec failure-rule text used when the session produced no value.
  final String? missingReason;

  /// Decision threshold τ for probabilities (IMG-10 uncertain zone ±0.10).
  final double? threshold;

  bool get isProbability => threshold != null;
  bool get memberFacing =>
      display == MarkerDisplay.shown || display == MarkerDisplay.bandOnly;

  String get validRangeLabel {
    if (validMin == null && validMax == null) return '';
    String f(double v) => v == v.roundToDouble() && v.abs() < 1e6
        ? v.toInt().toString()
        : v.toStringAsFixed(decimals.clamp(1, 3));
    final lo = validMin == null ? '' : f(validMin!);
    final hi = validMax == null ? '' : f(validMax!);
    return '$lo–$hi${unit.isEmpty ? '' : ' $unit'}';
  }

  bool matches(String key) => key == code || aliases.contains(key);
}

/// One algorithm card from Doc 09 (sections 4–10).
class AlgorithmCard {
  const AlgorithmCard({
    required this.id,
    required this.title,
    required this.specRef,
    required this.classification,
    required this.purpose,
    required this.outputs,
    this.failureRule = '',
    this.uiScreens = const [],
  });

  final String id;
  final String title;
  final String specRef;
  final String classification;
  final String purpose;
  final List<MarkerSpec> outputs;
  final String failureRule;
  final List<String> uiScreens;

  List<MarkerSpec> get memberOutputs =>
      outputs.where((o) => o.memberFacing).toList();
  List<MarkerSpec> get internalOutputs =>
      outputs.where((o) => !o.memberFacing).toList();
}

