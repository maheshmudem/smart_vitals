import 'enums.dart';

class ScreenSpec {
  const ScreenSpec({
    required this.screenId,
    required this.groupCode,
    required this.title,
    required this.purpose,
    required this.provenanceTag,
    required this.featureId,
    required this.entryGates,
    required this.runtimeGates,
    required this.lifecycleStates,
    required this.algorithmsUsed,
    required this.routeSummary,
  });

  final String screenId;
  final String groupCode;
  final String title;
  final String purpose;
  final String provenanceTag; // DOC, DER, STD, OPEN
  final String featureId;
  final List<GateId> entryGates;
  final List<GateId> runtimeGates;
  final List<FeatureLifecycleState> lifecycleStates;
  final List<String> algorithmsUsed;
  final String routeSummary;
}

class ScreeningCatalogueItem {
  const ScreeningCatalogueItem({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.category,
    required this.durationLabel,
    required this.hardwareNeeded,
    required this.featureId,
    required this.targetScreenId,
    required this.requiredGates,
    required this.algorithmIds,
    this.imageScreenType,
    this.minAgeYears,
    this.maxAgeYears,
    this.forNewbornOnly = false,
    this.releaseStatus = AlgorithmReleaseStatus.validated,
  });

  final String id;
  final String title;
  final String subtitle;
  final String category;
  final String durationLabel;
  final String hardwareNeeded;
  final String featureId;
  final String targetScreenId;
  final List<GateId> requiredGates;
  final List<String> algorithmIds;
  final ImageScreenType? imageScreenType;
  final int? minAgeYears;
  final int? maxAgeYears;
  final bool forNewbornOnly;
  final AlgorithmReleaseStatus releaseStatus;
}

